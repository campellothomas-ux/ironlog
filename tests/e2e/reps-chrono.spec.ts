import {test,expect,type Page} from '@playwright/test';
const KEY='ironlog-v4-prototype-2026-11-06';
async function workout(page:Page){
 await page.clock.install({time:new Date('2026-11-09T12:00:00Z')});
 await page.goto('/');await page.locator('[data-a="home-start"]').click();
}
const state=(page:Page)=>page.evaluate(k=>JSON.parse(localStorage.getItem(k)!),KEY);
test('un exercice personnalisé passe de REPS à CHRONO avec 5 secondes de transition bilatérale',async({page})=>{
 await workout(page);
 const before=await state(page);
 await page.locator('[data-a="replace-ex"]').click();
 await page.locator('[data-a="replace-create"]').click();
 await page.locator('#custom-ex-name').fill('Gainage latéral personnalisé');
 await page.locator('[data-a="replace-create-save"]').click();
 await page.locator('[data-a="wheel"][data-f="reps"]').click();
 await expect(page.getByRole('group',{name:'Mode de l\'exercice'})).toBeVisible();
 await page.locator('[data-a="wheel-mode"][data-mode="chrono"]').click();
 await expect(page.locator('[data-a="wheel-mode"][data-mode="chrono"]')).toHaveAttribute('aria-pressed','true');
 await page.locator('#wheel-per-side').check();
 await page.locator('#wheel-direct').fill('30');
 await page.locator('[data-a="wheel-save"]').click();
 const s=await state(page);
 const ex=s.workout.exercises[0];
 expect(ex.sets).toHaveLength(4);
 expect(ex.sets.map((x:{durationSeconds:number})=>x.durationSeconds)).toEqual([30,30,30,30]);
 expect(ex.sets[0]).toMatchObject({reps:0,perSide:true,transitionSeconds:5,sideOrder:['left','right'],rest:120});
 expect(s.programs).toEqual(before.programs);
 await expect(page.locator('[data-a="prep-timer"]')).toBeVisible();
 await page.locator('[data-a="prep-timer"]').click();
 await expect(page.locator('[data-execution-time]')).toHaveText('0:30');
 await page.clock.fastForward(30000);
 await expect(page.locator('.page.workout')).toContainText('CHANGE DE CÔTÉ');
 await page.clock.fastForward(5000);
 await expect(page.locator('.page.workout')).toContainText('TRAVAIL DROIT');
 await page.clock.fastForward(30000);
 await expect(page.locator('[data-execution-time]')).toHaveText('2:00');
});
test('le minuteur doit être arrêté avant de changer la durée ou revenir aux répétitions',async({page})=>{
 await workout(page);
 await page.locator('[data-a="wheel"][data-f="reps"]').first().click();
 await page.locator('[data-a="wheel-mode"][data-mode="chrono"]').click();
 await page.locator('#wheel-direct').fill('40');
 await page.locator('[data-a="wheel-save"]').click();
 await page.locator('[data-a="prep-timer"]').click();
 await page.locator('[data-a="wheel"][data-f="reps"]').click();
 await page.locator('[data-a="wheel-mode"][data-mode="reps"]').click();
 await page.locator('#wheel-direct').fill('12');
 await page.locator('[data-a="wheel-save"]').click();
 await expect(page.getByRole('status')).toContainText('Mets fin au minuteur');
 expect((await state(page)).workout.exercises[0].sets[0].durationSeconds).toBe(40);
 await page.locator('[data-a="wheel-cancel"]').click();
 await page.locator('[data-action="stop"]').click();
 await page.locator('[data-a="wheel"][data-f="reps"]').click();
 await page.locator('[data-a="wheel-mode"][data-mode="reps"]').click();
 await page.locator('#wheel-direct').fill('12');
 page.once('dialog',d=>d.accept());
 await page.locator('[data-a="wheel-save"]').click();
 const ex=(await state(page)).workout.exercises[0];
 expect(ex.sets.every((s:{durationSeconds?:number,reps:number,done:boolean})=>s.durationSeconds===undefined&&s.reps===12&&!s.done)).toBe(true);
 expect(ex.execution).toBeUndefined();
 await expect(page.locator('.valuebox').nth(1)).toContainText('12');
});
test('la valeur REPS reste modifiable par série sans conversion implicite',async({page})=>{
 await workout(page);
 await page.locator('[data-a="wheel"][data-f="reps"]').click();
 await expect(page.locator('[data-a="wheel-mode"][data-mode="reps"]')).toHaveAttribute('aria-pressed','true');
 await page.locator('#wheel-direct').fill('7');
 await page.locator('[data-a="wheel-save"]').click();
 const ex=(await state(page)).workout.exercises[0];
 expect(ex.sets[0].reps).toBe(7);
 expect(ex.sets[1].reps).toBe(6);
 expect(ex.sets[0].durationSeconds).toBeUndefined();
});
test('chronométrage simple et paramètres de repos restent disponibles',async({page})=>{
 await workout(page);
 await page.locator('[data-a="wheel"][data-f="reps"]').click();
 await page.locator('[data-a="wheel-mode"][data-mode="chrono"]').click();
 await page.locator('#wheel-direct').fill('45');
 await page.locator('[data-a="wheel-save"]').click();
 let ex=(await state(page)).workout.exercises[0];
 expect(ex.sets[0]).toMatchObject({durationSeconds:45,perSide:false});
 await page.locator('[data-a="wheel"][data-f="rest"]').click();
 await page.locator('#wheel-direct').fill('75');
 await page.locator('[data-a="wheel-save"]').click();
 ex=(await state(page)).workout.exercises[0];
 expect(ex.sets[0].rest).toBe(75);
 await page.reload();await page.locator('[data-a="resume"]').click();
 await expect(page.locator('[data-a="prep-timer"]')).toBeVisible();
 await page.locator('[data-a="wheel"][data-f="reps"]').click();
 await expect(page.locator('[data-a="wheel-mode"][data-mode="chrono"]')).toHaveAttribute('aria-pressed','true');
 await expect(page.locator('#wheel-direct')).toHaveValue('45');
});
