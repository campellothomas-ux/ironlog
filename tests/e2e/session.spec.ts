import { test, expect } from '@playwright/test';
const key='ironlog-v4-prototype-2026-11-06';
test('confirmation, modes et roues cohérents, une activité persistante',async({page})=>{
  await page.goto('/');
  await page.locator('[data-a="home-start"]').click();
  await page.locator('[data-a="wheel"][data-f="kg"]').click();
  await page.locator('#wheel-direct').fill('72.5');
  await page.locator('[data-a="wheel-save"]').click();
  await page.locator('[data-a="toggle-mode"]').click();
  await expect(page.locator('.details-row').first()).toContainText('72,5');
  await page.locator('[data-a="toggle-mode"]').click();
  await expect(page.locator('.valuebox').first()).toContainText('72.5');
  await expect(page.locator('.set-pips .pip').last()).toBeVisible();
  page.once('dialog',dialog=>dialog.dismiss());
  await page.locator('[data-a="work-finish"]').click();
  await expect(page.locator('.page.workout')).toBeVisible();
  page.once('dialog',dialog=>dialog.accept());
  await page.locator('[data-a="work-finish"]').dblclick();
  await expect(page.locator('#activities-list .activity')).toHaveCount(1);
  await page.reload();
  await page.locator('[data-nav="you"]').click();
  await expect(page.locator('#activities-list .activity')).toHaveCount(1);
  const saved=await page.evaluate(key=>JSON.parse(localStorage.getItem(key)!),key);
  expect(saved.workout).toBeNull();
  expect(saved.history[0].exercises[0].sets[0].kg).toBe(72.5);
});
test('échec de stockage visible, séance conservée et réessai réussi',async({page})=>{
  await page.goto('/');
  await page.locator('[data-a="home-start"]').click();
  await page.evaluate(()=>{Storage.prototype.setItem=function(){throw new DOMException('Full','QuotaExceededError');};});
  page.once('dialog',dialog=>dialog.accept());
  await page.locator('[data-a="work-finish"]').click();
  await expect(page.getByRole('status')).toContainText('Enregistrement impossible');
  await expect(page.locator('.page.workout')).toBeVisible();
  await page.reload();
  await page.locator('[data-a="resume"]').click();
  page.once('dialog',dialog=>dialog.accept());
  await page.locator('[data-a="work-finish"]').click();
  await expect(page.locator('#activities-list .activity')).toHaveCount(1);
});
